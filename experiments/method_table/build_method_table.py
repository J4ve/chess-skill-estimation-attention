"""Write src/static/suspicion_methods.json, the page's table of suspicion-score
methods: plain-language labels, descriptions and each method's own measured
ROC-AUCs, which the page turns into its captions and info text.

Numbers are copied from their sources, never typed in: the trained detectors'
headline_auc blocks in src/models/*.json, and S_att's grouped-split AUCs from
headline_auc.json (headline_auc.py, HPC). All four come from the same synthetic
anomaly corpus v2 conditions.

  python experiments/method_table/build_method_table.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
MODELS = ROOT / "src" / "models"

CONDITIONS = {
    "withheld_band": "withheld_band",
    "rate02": "withheld_band_rate02_vs_clean",
    "rate05": "withheld_band_rate05_vs_clean",
    "rate60": "withheld_band_rate60_vs_clean",
    "seen": "seen",
}


def pick(block):
    return {short: round(block[key]["auc"], 3) for short, key in CONDITIONS.items()}


headline = json.loads((HERE / "headline_auc.json").read_text())
prov = {name: json.loads((MODELS / f"{name}.json").read_text())
        for name in ("detector_lgbm_a0g", "detector_a3g_seed0", "detector_cnn_bilstm_a4")}
a3g = prov["detector_a3g_seed0"]["headline_auc"]

methods = [
    {
        "id": "s_att",
        "label": "Computed score (first method tried)",
        "short_label": "Computed score",
        "arm": "S_att",
        "scale": "rating_points",
        "description": "The first method tried: the attention-weighted average gap, in rating points, between the rating model's per-move estimate and the player's baseline. It has no trained parameters.",
        "caveat": "It separated engine-substituted games at about chance, so it is shown for comparison only.",
        "split": "grouped",
        "auc": pick(headline["s_att_grouped"]),
    },
    {
        "id": "lgbm_a0g",
        "label": "Trained detector (LightGBM)",
        "short_label": "LightGBM detector",
        "arm": "A0g",
        "scale": "unit",
        "description": "A gradient-boosted tree model scoring 0 to 1 from 97 whole-game summaries of the rating model's per-move estimates and attention plus simple board and clock facts.",
        "caveat": "",
        "split": prov["detector_lgbm_a0g"]["split"],
        "auc": pick(prov["detector_lgbm_a0g"]["headline_auc"]),
    },
    {
        "id": "detector_a3g_seed0",
        "label": "Per-move detector (A3g, default)",
        "short_label": "Per-move detector",
        "arm": "A3g",
        "scale": "unit",
        "description": "A small recurrent network scoring 0 to 1 from the rating model's per-move estimates and attention plus simple board and clock facts, read move by move. It measured best of the four on rating bands withheld from training.",
        "caveat": "",
        "split": prov["detector_a3g_seed0"]["split"],
        "auc": {short: round(a3g[key]["auc"], 3) for short, key in {
            "withheld_band": "withheld_band", "rate02": "withheld_band_rate02_vs_clean",
            "rate05": "withheld_band_rate05_vs_clean", "rate60": "withheld_band_rate60_vs_clean",
            "seen": "seen_test"}.items()},
    },
    {
        "id": "cnn_bilstm_a4",
        "label": "Full model (CNN-BiLSTM)",
        "short_label": "CNN-BiLSTM detector",
        "arm": "A4",
        "scale": "unit",
        "description": "A fine-tuned copy of the rating model itself scoring 0 to 1 straight from the board positions and clocks, move by move.",
        "caveat": "It trained on a split that was not twin-safe, so its withheld-band result is the fair comparison; a board-level model can also learn to spot engine-style moves directly.",
        "split": prov["detector_cnn_bilstm_a4"]["split"],
        "auc": pick(prov["detector_cnn_bilstm_a4"]["headline_auc"]),
    },
]

table = {
    "note": "Generated by experiments/method_table/build_method_table.py; do not edit by hand. auc values are ROC-AUC on the synthetic anomaly corpus v2: withheld_band = rating bands 1300 and 1700, never seen in training (all substitution rates); rateNN = those bands at NN percent engine moves vs clean games; seen = the test partition of the training bands.",
    "default_method": "detector_a3g_seed0",
    "critical_moves_note": "Critical moves and chart markers always rank by attention times deviation, whatever method is selected: every trained detector's per-move output localized engine moves at or below chance.",
    "methods": methods,
}
(ROOT / "src" / "static" / "suspicion_methods.json").write_text(json.dumps(table, indent=2) + "\n")
for m in methods:
    print(m["id"], m["auc"])
